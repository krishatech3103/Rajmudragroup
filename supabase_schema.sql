CREATE OR REPLACE FUNCTION public.rajmudra_prevent_linked_fd_delete()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM public.bank_fd WHERE type = 'renew' AND renewed_from_id = OLD.id)
    OR (OLD.type IN ('bank_to_cash', 'bank_to_upi') AND EXISTS (SELECT 1 FROM public.bank_fd renewal WHERE renewal.type = 'renew' AND renewal.renewed_from_id = OLD.withdrawn_from_id))
  THEN RAISE EXCEPTION 'This entry is part of a completed FD renewal and cannot be deleted independently.' USING ERRCODE = 'P0001'; END IF;
  RETURN OLD;
END;
$$;
DROP TRIGGER IF EXISTS prevent_renewed_fd_source_delete ON public.bank_fd;
DROP TRIGGER IF EXISTS prevent_linked_fd_delete ON public.bank_fd;
CREATE TRIGGER prevent_linked_fd_delete BEFORE DELETE ON public.bank_fd FOR EACH ROW EXECUTE FUNCTION public.rajmudra_prevent_linked_fd_delete();

