CREATE OR REPLACE FUNCTION public.rajmudra_bank_balance(p_exclude_bank_fd_id BIGINT DEFAULT NULL)
RETURNS NUMERIC LANGUAGE sql STABLE SET search_path = public AS $$
  WITH entries AS (
    SELECT id, type, amount, renewed_from_id, withdrawn_from_id FROM public.bank_fd
    WHERE p_exclude_bank_fd_id IS NULL OR id <> p_exclude_bank_fd_id
  ), renewed_sources AS (
    SELECT renewed_from_id FROM entries WHERE type = 'renew' AND renewed_from_id IS NOT NULL
  )
  SELECT COALESCE(SUM(CASE
    WHEN id IN (SELECT renewed_from_id FROM renewed_sources) THEN 0
    WHEN type IN ('bank_to_cash', 'bank_to_upi') AND withdrawn_from_id IN (SELECT renewed_from_id FROM renewed_sources) THEN 0
    WHEN type IN ('deposit', 'renew', 'cash_to_bank', 'upi_to_bank', 'interest', 'bank_income') THEN amount
    WHEN type IN ('withdrawal', 'bank_to_cash', 'bank_to_upi', 'fd_expense', 'charge', 'bank_expense') THEN -amount
    ELSE 0 END), 0) FROM entries;
$$;

CREATE OR REPLACE FUNCTION public.rajmudra_treasury_balances(
  p_year TEXT, p_exclude_kharch_id BIGINT DEFAULT NULL, p_exclude_bank_fd_id BIGINT DEFAULT NULL
)
RETURNS TABLE (cash_balance NUMERIC, online_balance NUMERIC)
LANGUAGE sql STABLE SET search_path = public AS $$
  WITH income AS (
    SELECT payment_mode, amount FROM public.vargani WHERE year = p_year AND COALESCE(status, 'paid') = 'paid'
    UNION ALL SELECT payment_mode, amount FROM public.jama WHERE year = p_year
  ), expenses AS (
    SELECT payment_mode, amount FROM public.kharch WHERE year = p_year AND (p_exclude_kharch_id IS NULL OR id <> p_exclude_kharch_id)
  ), movements AS (
    SELECT type, amount, renewal_extra_amount, renewal_extra_source FROM public.bank_fd
    WHERE year = p_year AND (p_exclude_bank_fd_id IS NULL OR id <> p_exclude_bank_fd_id)
  )
  SELECT
    COALESCE((SELECT SUM(CASE WHEN LOWER(BTRIM(COALESCE(payment_mode, 'Cash'))) = 'cash' THEN amount ELSE 0 END) FROM income), 0)
      - COALESCE((SELECT SUM(CASE WHEN LOWER(BTRIM(COALESCE(payment_mode, 'Cash'))) = 'cash' THEN amount ELSE 0 END) FROM expenses), 0)
      + COALESCE((SELECT SUM(CASE WHEN type IN ('upi_to_cash', 'bank_to_cash') THEN amount WHEN type IN ('cash_to_upi', 'cash_to_bank') THEN -amount WHEN type = 'renew' AND renewal_extra_source = 'Cash' THEN -renewal_extra_amount ELSE 0 END) FROM movements), 0),
    COALESCE((SELECT SUM(CASE WHEN LOWER(BTRIM(COALESCE(payment_mode, 'Cash'))) <> 'cash' THEN amount ELSE 0 END) FROM income), 0)
      - COALESCE((SELECT SUM(CASE WHEN LOWER(BTRIM(COALESCE(payment_mode, 'Cash'))) <> 'cash' THEN amount ELSE 0 END) FROM expenses), 0)
      + COALESCE((SELECT SUM(CASE WHEN type IN ('cash_to_upi', 'bank_to_upi') THEN amount WHEN type IN ('upi_to_cash', 'upi_to_bank') THEN -amount WHEN type = 'renew' AND renewal_extra_amount > 0 AND renewal_extra_source = 'UPI' THEN -renewal_extra_amount ELSE 0 END) FROM movements), 0);
$$;

CREATE OR REPLACE FUNCTION public.rajmudra_validate_expense_balance()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = public AS $$
DECLARE balances RECORD; available NUMERIC; old_id BIGINT := NULL;
BEGIN
  IF TG_OP = 'UPDATE' THEN old_id := OLD.id; END IF;
  PERFORM pg_advisory_xact_lock(hashtext('rajmudra:treasury:' || NEW.year));
  SELECT * INTO balances FROM public.rajmudra_treasury_balances(NEW.year, old_id, NULL);
  available := CASE WHEN LOWER(BTRIM(COALESCE(NEW.payment_mode, 'Cash'))) = 'cash' THEN balances.cash_balance ELSE balances.online_balance END;
  IF NEW.amount > available THEN RAISE EXCEPTION 'Insufficient % balance. Available: Rs. %', NEW.payment_mode, available USING ERRCODE = 'P0001'; END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.rajmudra_validate_bank_entry_balance()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = public AS $$
DECLARE balances RECORD; available NUMERIC; bank_before NUMERIC; bank_after NUMERIC; source_available NUMERIC; old_id BIGINT := NULL; bank_delta NUMERIC := 0;
BEGIN
  IF TG_OP = 'UPDATE' THEN old_id := OLD.id; END IF;
  PERFORM pg_advisory_xact_lock(hashtext('rajmudra:bank'));
  PERFORM pg_advisory_xact_lock(hashtext('rajmudra:treasury:' || NEW.year));
  IF TG_OP = 'UPDATE' AND (
    EXISTS (SELECT 1 FROM public.bank_fd WHERE type = 'renew' AND renewed_from_id = OLD.id)
    OR EXISTS (SELECT 1 FROM public.bank_fd withdrawal WHERE withdrawal.type IN ('bank_to_cash', 'bank_to_upi') AND withdrawal.withdrawn_from_id = OLD.id)
    OR (OLD.type IN ('bank_to_cash', 'bank_to_upi') AND EXISTS (SELECT 1 FROM public.bank_fd renewal WHERE renewal.type = 'renew' AND renewal.renewed_from_id = OLD.withdrawn_from_id))
  ) THEN RAISE EXCEPTION 'This entry is part of a completed FD renewal and cannot be changed.' USING ERRCODE = 'P0001'; END IF;
  IF NEW.type IN ('cash_to_bank', 'upi_to_bank') THEN
    SELECT * INTO balances FROM public.rajmudra_treasury_balances(NEW.year, NULL, old_id);
    available := CASE WHEN NEW.type = 'cash_to_bank' THEN balances.cash_balance ELSE balances.online_balance END;
    IF NEW.amount > available THEN RAISE EXCEPTION 'Insufficient source balance. Available: Rs. %', available USING ERRCODE = 'P0001'; END IF;
  END IF;
  IF NEW.type IN ('bank_to_cash', 'bank_to_upi') THEN
    IF NEW.withdrawn_from_id IS NULL THEN RAISE EXCEPTION 'Select the FD being withdrawn.' USING ERRCODE = 'P0001'; END IF;
    SELECT source.amount - COALESCE((SELECT SUM(withdrawal.amount) FROM public.bank_fd withdrawal WHERE withdrawal.type IN ('bank_to_cash', 'bank_to_upi') AND withdrawal.withdrawn_from_id = source.id AND (old_id IS NULL OR withdrawal.id <> old_id)), 0)
      INTO source_available FROM public.bank_fd source WHERE source.id = NEW.withdrawn_from_id AND source.type IN ('deposit', 'renew', 'cash_to_bank', 'upi_to_bank')
        AND NOT EXISTS (SELECT 1 FROM public.bank_fd later_renewal WHERE later_renewal.type = 'renew' AND later_renewal.renewed_from_id = source.id);
    IF source_available IS NULL OR NEW.amount > source_available THEN RAISE EXCEPTION 'Insufficient balance in the selected FD. Available: Rs. %', COALESCE(source_available, 0) USING ERRCODE = 'P0001'; END IF;
  END IF;
  bank_before := public.rajmudra_bank_balance(old_id);
  IF NEW.type = 'renew' THEN
    IF NEW.renewed_from_id IS NULL THEN RAISE EXCEPTION 'Select the old FD being renewed.' USING ERRCODE = 'P0001'; END IF;
    SELECT source.amount - COALESCE((SELECT SUM(withdrawal.amount) FROM public.bank_fd withdrawal WHERE withdrawal.type IN ('bank_to_cash', 'bank_to_upi') AND withdrawal.withdrawn_from_id = source.id), 0)
      INTO source_available FROM public.bank_fd source WHERE source.id = NEW.renewed_from_id AND source.type IN ('deposit', 'renew', 'cash_to_bank', 'upi_to_bank')
        AND NOT EXISTS (SELECT 1 FROM public.bank_fd later_renewal WHERE later_renewal.type = 'renew' AND later_renewal.renewed_from_id = source.id AND (old_id IS NULL OR later_renewal.id <> old_id));
    IF source_available IS NULL THEN RAISE EXCEPTION 'The selected FD is unavailable for renewal.' USING ERRCODE = 'P0001'; END IF;
    IF NEW.amount < source_available + NEW.renewal_extra_amount THEN RAISE EXCEPTION 'The renewed total must include the selected FD balance and any top-up.' USING ERRCODE = 'P0001'; END IF;
    IF NEW.renewal_extra_amount > 0 THEN
      SELECT * INTO balances FROM public.rajmudra_treasury_balances(NEW.year, NULL, old_id);
      available := CASE WHEN NEW.renewal_extra_source = 'Cash' THEN balances.cash_balance ELSE balances.online_balance END;
      IF NEW.renewal_extra_amount > available THEN RAISE EXCEPTION 'Insufficient % balance for the renewal top-up. Available: Rs. %', NEW.renewal_extra_source, available USING ERRCODE = 'P0001'; END IF;
    END IF;
    bank_after := bank_before - source_available + NEW.amount;
  ELSE
    bank_delta := CASE WHEN NEW.type IN ('deposit', 'cash_to_bank', 'upi_to_bank', 'interest', 'bank_income') THEN NEW.amount WHEN NEW.type IN ('withdrawal', 'bank_to_cash', 'bank_to_upi', 'fd_expense', 'charge', 'bank_expense') THEN -NEW.amount ELSE 0 END;
    bank_after := bank_before + bank_delta;
  END IF;
  IF bank_after < 0 THEN RAISE EXCEPTION 'Insufficient Bank / FD balance. Available: Rs. %', bank_before USING ERRCODE = 'P0001'; END IF;
  RETURN NEW;
END;
$$;

