-- ====================================================================
-- PERFORMANCE INDEXES
-- ====================================================================
-- The client fetches a fiscal year ordered by entry date. These composite
-- indexes avoid full-table scans as ledger history grows.
CREATE INDEX IF NOT EXISTS idx_vargani_year_date ON public.vargani(year, date DESC);
CREATE INDEX IF NOT EXISTS idx_vargani_member_id ON public.vargani(member_id);
CREATE INDEX IF NOT EXISTS idx_jama_year_date ON public.jama(year, date DESC);
CREATE INDEX IF NOT EXISTS idx_kharch_year_date ON public.kharch(year, date DESC);
CREATE INDEX IF NOT EXISTS idx_aarti_year_date ON public.aarti(year, date ASC);
CREATE INDEX IF NOT EXISTS idx_bank_fd_year_date ON public.bank_fd(year, date DESC);

-- ====================================================================
-- REALTIME PUBLICATION
-- ====================================================================
-- This is safe to rerun and enables table-change subscriptions when the
-- Supabase project has its normal `supabase_realtime` publication.
DO $$
DECLARE
    target_table TEXT;
BEGIN
    IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
        FOREACH target_table IN ARRAY ARRAY['members', 'vargani', 'jama', 'kharch', 'aarti', 'bank_fd', 'app_settings']
        LOOP
            IF NOT EXISTS (
                SELECT 1
                FROM pg_publication_tables
                WHERE pubname = 'supabase_realtime'
                  AND schemaname = 'public'
                  AND tablename = target_table
            ) THEN
                EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I', target_table);
            END IF;
        END LOOP;
    END IF;
END $$;

