-- Upgrade the original `BIGINT PRIMARY KEY` columns to generated identities
-- without changing their type or existing values.
DO $$
DECLARE
    target_table TEXT;
BEGIN
    FOREACH target_table IN ARRAY ARRAY['members', 'vargani', 'jama', 'kharch', 'aarti', 'bank_fd']
    LOOP
        IF NOT EXISTS (
            SELECT 1
            FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = target_table
              AND column_name = 'id'
              AND is_identity = 'YES'
        ) THEN
            EXECUTE format(
                'ALTER TABLE public.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY',
                target_table
            );
        END IF;
    END LOOP;
END $$;

-- Align every newly-created identity sequence with existing rows. This avoids
-- a generated ID colliding with an older explicit ID.
DO $$
DECLARE
    target_table TEXT;
    sequence_name TEXT;
BEGIN
    FOREACH target_table IN ARRAY ARRAY['members', 'vargani', 'jama', 'kharch', 'aarti', 'bank_fd']
    LOOP
        sequence_name := pg_get_serial_sequence(format('public.%I', target_table), 'id');
        IF sequence_name IS NOT NULL THEN
            EXECUTE format(
                'SELECT setval(%L, COALESCE(MAX(id), 1), COUNT(*) > 0) FROM public.%I',
                sequence_name,
                target_table
            );
        END IF;
    END LOOP;
END $$;

-- Keep updated_at current for direct mutations, including those made outside
-- the frontend.
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS set_members_updated_at ON public.members;
