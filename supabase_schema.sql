-- ====================================================================
-- RAJMUDRA GROUP PWA - SUPABASE-ONLY SCHEMA AND SAFE MIGRATION
-- ====================================================================
-- Run this in the Supabase SQL Editor before deploying the Supabase-only
-- frontend. It is additive: it does not delete existing ledger rows.
--
-- Migration notes
-- 1. Take a Supabase backup first.
-- 2. Existing BIGINT primary keys are retained. `BY DEFAULT` identity
--    columns accept old client-supplied IDs during the transition, while
--    the new client can omit `id` and receive a database-generated value.
-- 3. The identity sequences are advanced beyond existing IDs, so they do
--    not collide with legacy Date.now()-style values.
-- 4. After the frontend rollout, treat Supabase as the only source of
--    truth; do not import stale browser-storage backups automatically.
-- ====================================================================

-- 1. Members
CREATE TABLE IF NOT EXISTS public.members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL DEFAULT '',
    address TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Vargani (donations)
CREATE TABLE IF NOT EXISTS public.vargani (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prefix TEXT NOT NULL DEFAULT 'श्री',
    member_id BIGINT,
    member_name TEXT NOT NULL,
    phone TEXT NOT NULL DEFAULT '',
    year TEXT NOT NULL,
    amount NUMERIC NOT NULL,
    payment_mode TEXT NOT NULL DEFAULT 'Cash',
    status TEXT NOT NULL DEFAULT 'paid',
    date DATE NOT NULL,
    receipt_no TEXT NOT NULL DEFAULT '',
    note TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Jama (income)
CREATE TABLE IF NOT EXISTS public.jama (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL,
    year TEXT NOT NULL,
    amount NUMERIC NOT NULL,
    payment_mode TEXT NOT NULL DEFAULT 'Cash',
    date DATE NOT NULL,
    note TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Kharch (expenses)
CREATE TABLE IF NOT EXISTS public.kharch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL,
    year TEXT NOT NULL,
    amount NUMERIC NOT NULL,
    payment_mode TEXT NOT NULL DEFAULT 'Cash',
    date DATE NOT NULL,
    note TEXT NOT NULL DEFAULT '',
    is_locked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. Aarti schedule
CREATE TABLE IF NOT EXISTS public.aarti (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year TEXT NOT NULL,
    day_title TEXT NOT NULL,
    date DATE NOT NULL,
    morning_time TEXT NOT NULL DEFAULT '09.00 AM',
    morning_host TEXT NOT NULL DEFAULT '',
    evening_time TEXT NOT NULL DEFAULT '08.00 PM',
    evening_host TEXT NOT NULL DEFAULT '',
    note TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 6. Bank FD and treasury
CREATE TABLE IF NOT EXISTS public.bank_fd (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    type TEXT NOT NULL DEFAULT 'cash_to_bank' CHECK (type IN ('cash_to_bank', 'upi_to_bank', 'bank_to_cash', 'bank_to_upi', 'renew')),
    year TEXT NOT NULL,
    amount NUMERIC NOT NULL,
    interest_rate NUMERIC NOT NULL DEFAULT 0,
    expected_returns NUMERIC NOT NULL DEFAULT 0,
    bank_name TEXT NOT NULL DEFAULT 'Mandal Bank FD Account',
    date DATE NOT NULL,
    expiry_date DATE,
    renewed_from_id BIGINT REFERENCES public.bank_fd(id),
    withdrawn_from_id BIGINT REFERENCES public.bank_fd(id),
    renewal_extra_amount NUMERIC NOT NULL DEFAULT 0,
    renewal_extra_source TEXT NOT NULL DEFAULT '',
    holder_name TEXT NOT NULL DEFAULT '',
    note TEXT NOT NULL DEFAULT '',
    is_locked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

